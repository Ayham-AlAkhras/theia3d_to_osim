# This script maps coordinates for the TLO model (generated by Script 4) to
# coordinates for a separately scaled Rajagopal2016 model. Theia3D’s and
# Rajagopal’s human kinematic models represent human movement differently. This
# difference is not inferable using the publicly available documentation for
# both models. Therefore, this script uses temporally synchronized marker and
# markerless data to calculate the average difference between the two models. It
# then uses that average difference to offset the markerless data, translating
# them to joint angles in the OpenSim model that represent the same human
# motion. If you wish to use this workflow in the absence of marker data, you
# can do so using the default offsets we have provided. These offsets were
# averaged from 40 participants (22 females) each walking continuously at steady
# state for 12 gait cycles starting at heel-strike.
#
# This script was built using OpenSim 4.5 and Python 3.11 and tested with data
# from Theia3D 2022.2.
#
# version 1.0

