# Read motion file and store in a DataFrame.
def readMotFile(aFilename, aPrintStatus = False):
    
    # Read file header and column headers.
    numHeadRows = 1
    numDataRows = 0
    numDataCols = 0
    inDegrees = -1
    foundEndHeader = False
    
    f = open(aFilename, 'r')
    
    while f:
        line = f.readline()
        if ('nRows' in line):
            numDataRows = int( line[line.index('=')+1:] )
        if ('nColumns' in line):
            numDataCols = int( line[line.index('=')+1:] )
        if ('inDegrees' in line):
            if '=yes' in line:
                inDegrees = True
            elif '=no' in line:
                inDegrees = False
        if ('endheader' in line):
            foundEndHeader = True
            continue
        if (not foundEndHeader):
            numHeadRows += 1
        else:
            line = line.strip()  #remove trailing line break
            colHeaders = line.split('\t')
            break
    
    f.close()
    
    # Report file info (for debugging).
    if (aPrintStatus):
        print('** Header rows detected: {}'.format(numHeadRows))
        print('** Data table size: {} rows, {} columns'
              .format(numDataRows, numDataCols))
        print('** Columns:')
        for i in range(numDataCols):
            print('   [{}]: {}'.format(i, colHeaders[i]))
    
    # Read data into DataFrame.
    df = pandas.read_csv(aFilename, delimiter='\t', skiprows=numHeadRows)
    if ((df.shape[0] != numDataRows) or (df.shape[1] != numDataCols)):
        raise Exception('DataFrame dimensions inconsistent with file header')
    
    # Make sure inDegrees is defined, assign it to df metadata.
    if inDegrees == -1:
        raise Exception('Unknown if file is in degrees or radians')
    else:
        df.inDegrees = inDegrees
    
    return df

class MotFileGenerator:
    def __init__(self,
                 fileName   : str,
                 nTimeSteps : int,
                 model      : osim.Model,
                 title = ''):
        
        self.coordFile = open(fileName, 'w')
        self.model = model
        nCoords = self.model.getNumCoordinates()
        coordSet = self.model.getCoordinateSet()
        
        if title == '':
            title = os.path.basename(fileName)
        
        self.coordFile.write(
                        os.path.splitext(title)[0]+'\n'
                         'version=1\n'
                        f'nRows={nTimeSteps}\n'
                        f'nColumns={nCoords+1}\n'
                         'inDegrees=yes\n'
                         '\n'
                         'Units are S.I. units (second, meters, Newtons, ...)\n'
                         "If the header above contains a line with 'inDegrees',"
                         ' this indicates whether rotational values are in'
                         ' degrees (yes) or radians (no).\n'
                         '\n'
                         'endheader\n')
        
        # Write column labels for the IK results.
        string = 'time\t'
        for coordIndex in range(nCoords):
            coord = coordSet.get(coordIndex)
            coordName = coord.getName()
            stringEnd = '\t' if (coordIndex < nCoords-1) else '\n'
            string = string + coordName + stringEnd
        self.coordFile.write(string)
        
    def writeTimeStep(self,
                      state : osim.State):
        self.model.realizePosition(state)
        nCoords = self.model.getNumCoordinates()
        coordSet = self.model.getCoordinateSet()
        time = state.getTime()
        timeFormatted = '{:.8f}'.format(time)
        string = f'      {timeFormatted}\t     '
        for coordIndex in range(nCoords):
            coord = coordSet.get(coordIndex)
            coordValue = coord.getValue(state)
            if (coord.getMotionType()==1):
                    coordValue = coordValue * (180 / np.pi)
            coordValueFormatted = '{:.8f}'.format(coordValue)
            stringEnd = '\t      ' if (coordIndex < nCoords - 1) else '\n'
            string = string + str(coordValueFormatted) + stringEnd
        self.coordFile.write(string)
    
    def close(self):
        self.coordFile.close()

# Find if a coordinate name exists in a model, useful when looking for common
# coordinates between two different models.
def coordinateNameInModel(coordName : str,
                          model : osim.Model):
    coordSet = model.getCoordinateSet()
    for c in range(model.getNumCoordinates()):
        mdlCoordName = coordSet.get(c).getName()
        if (coordName == mdlCoordName):
            return True
    return False

def trimDf(self: pandas.DataFrame,
           startTime: float,
           endTime: float,
           timeLabel = 'time'):
    '''
    Trim a DataFrame using a time column, start time, and end time.
    
    :param startTime: The starting time (inclusive).
    :param endTime: The end time (inclusive).
    :param timeLabel: The label for the time column in the DataFrame.
    :returns: The trimmed DataFrame.
    '''
    
    timeSeries = self[timeLabel]
    
    startDif = timeSeries.astype(float).copy() - startTime
    endDif = timeSeries.astype(float).copy() - endTime
    
    startIndex = startDif.abs().argmin()
    endIndex = endDif.abs().argmin()
    
    inDegrees = self.inDegrees
    
    # Trimming an array-like with indices in Python uses indices that are
    # [inclusive:exclusive] (because Python is weird). The +1 makes it
    # [inclusive:inclusive].
    self = self[startIndex:endIndex+1]

    self = self.reset_index(drop=True,inplace=False)
    
    self.inDegrees = inDegrees
    del inDegrees
    
    return self

# This method converts a Python list to an OpenSim quaternion. It checks that
# the quaternion is valid. Example: osim.Quaternion.createFromList([1,0,0,0])
def osimQuatCreateFromList(quaternionList : list):
    if not len(quaternionList) == 4:
        raise Exception("ERROR: Quaternion input not of length 4.")
    
    for i in range(4):
        if not isinstance(quaternionList[i], (int, float)):
            raise Exception("ERROR: Quaternion input not numeric.")
    
    quaternion = osim.Quaternion(quaternionList[0],
                                 quaternionList[1],
                                 quaternionList[2],
                                 quaternionList[3])
    
    for i in range(4):
        if abs(quaternion.get(i)-quaternionList[i]) > 0.00001:
            raise Exception("ERROR: Quaternion input not a valid quaternion.")
    
    return quaternion
osim.Quaternion.createFromList = osimQuatCreateFromList

# Compute individualized offsets.
def computeOffsets(tloDf : pandas.DataFrame,
                   tloModel : osim.Model,
                   sknDf : pandas.DataFrame,
                   sknModel : osim.Model,
                   offsetQuatDf : pandas.DataFrame,
                   offsetCartDf : pandas.DataFrame):
    
    sknState = sknModel.initSystem()
    sknCoordSet = sknModel.getCoordinateSet()
    sknFileCoords = sknDf.columns[1:]
    sknJointSet = sknModel.getJointSet()
    
    # tloNTimeSteps = tloDf.shape[0]
    tloFileCoords = tloDf.columns[1:]
    # tloTimeArray = tloDf['time']
    
    tloState    = tloModel.initSystem()
    tloCoordSet = tloModel.getCoordinateSet()
    
    if len(sknDf.index)<len(tloDf.index):
        dfUsed = sknDf
    else:
        dfUsed = tloDf
    timeArray = dfUsed['time']
    # Map TLO coordinates to Rajagopal coordinates for each time-step.
    for timeStep, timeSec in enumerate(timeArray):
        
        sknState.setTime(timeSec)
        tloState.setTime(timeSec)
        
        for coordName in sknFileCoords:
            coord = sknCoordSet.get(coordName)
            jointName = coord.getJoint().getName()
            coordNameFull = '/jointset/'+jointName+'/'+coordName+'/value'
            coordVal = sknDf.at[timeStep,coordName]
            # Convert rotational coordinates from degrees to radians.
            if (sknDf.inDegrees and coord.getMotionType()==1):
                coordVal = coordVal * np.pi/180
            coordVal = coordVal.astype(np.float64)
            sknModel.setStateVariableValue(sknState, coordNameFull, coordVal)
            
            # NOTE: method below not used because it takes 3x as long
            # coord.setValue(sknState,
            #                coordVal,
            #                True if c==len(sknFileCoords)-1 else False)
        
        # Set the TLO model coordinates at this time-step according to the IK
        # results.
        for coordName in tloFileCoords:
            coord = tloCoordSet.get(coordName)
            jointName = coord.getJoint().getName()
            coordNameFull = '/jointset/'+jointName+'/'+coordName+'/value'
            coordVal = tloDf.at[timeStep,coordName]
            # Convert rotational coordinates from degrees to radians.
            if (tloDf.inDegrees and coord.getMotionType()==1):
                coordVal = coordVal * np.pi/180
            coordVal = coordVal.astype(np.float64)
            tloModel.setStateVariableValue(tloState, coordNameFull, coordVal)
            
            # NOTE: method below not used because it takes 3x as long
            # coord.setValue(tloState,
            #                coordVal,
            #                True if c==len(tloFileCoords)-1 else False)
        
        # Realize positions to be able to extract rotation matrices of body frames.
        tloModel.realizePosition(tloState)
        sknModel.realizePosition(sknState)
        
        for j in range(sknModel.getNumJoints()):
            
            sknJoint = sknJointSet.get(j)
            sknJointName = sknJoint.getName()
            
            # Extract a coordinate from Rajagopal that also exists in TLO. Every
            # coordinate in Rajagopal (except for the patella coordinate) has an
            # equivalent TLO coordinate, so we just use the first coordinate of the
            # current joint. We use this coordinate to extract the 
            sknCoord = sknJoint.get_coordinates(0)
            try:
                commonCoord = tloCoordSet.get(sknCoord.getName())
            except:
                # print(f'WARNING: {sknCoord.getName()} not common between the two models.')
                continue
            
            # Using the coordinate that is common between TLO and Rajagopal, extract 
            # the TLO joint and child body for this Rajagopal joint.
            tloJoint = commonCoord.getJoint()
            tloChildName = tloJoint.getChildFrame().getName().replace('_offset','')
            tloChildBody = tloModel.getBodySet().get(tloChildName)
            
            sknChildName = sknJoint.getChildFrame().getName().replace('_offset','')
            sknChildBody = sknModel.getBodySet().get(sknChildName)
            
            # Obtain the rotation matrix for the offsets based on the skin-marker data.
            # We do this by defining an offset rotation matrix between the marker and
            # Theia data. We find these matrices at each time-step and convert the
            # them to quaternions.
            # We can then average these quaternions over all time-steps and convert the
            # result to a rotation matrix that is the individualized average offset
            # matrix for this subject.
            rotTloChild = tloChildBody.getRotationInGround(tloState)
            rotSknChild = sknChildBody.getRotationInGround(sknState)
            
            inv = rotTloChild.invert()
            rotTloChildInv = IDENTITY_ROT.multiply(inv)
            rotOffset = rotTloChildInv.multiply(rotSknChild)
            
            quatOffset = rotOffset.convertRotationToQuaternion()
            
            offsetQuatDf.at[timeSec,sknJointName+"_a"]  = quatOffset.get(0)
            offsetQuatDf.at[timeSec,sknJointName+"_vx"] = quatOffset.get(1)
            offsetQuatDf.at[timeSec,sknJointName+"_vy"] = quatOffset.get(2)
            offsetQuatDf.at[timeSec,sknJointName+"_vz"] = quatOffset.get(3)
            
            sknNCoords = sknJoint.numCoordinates()
            for c in range(sknNCoords):
                sknCoord = sknJoint.get_coordinates(c)
                coordName = sknCoord.getName()
                if sknCoord.getMotionType() == 2:
                    offsetCartDf.at[timeSec,coordName] = \
                        sknChildBody.getPositionInGround(sknState).get(c-3) \
                        - tloChildBody.getPositionInGround(tloState).get(c-3)
        
    # Average the quaternions over time.
    averagesQuat = {}
    averagesCart = {}
    offsetQuatNp = offsetQuatDf.to_numpy(dtype=float).copy()
    nQuat = (offsetQuatNp.shape[1] - 1) // 4  # Compute number of quaternions
    columnLabels = list(offsetQuatDf.columns)
    
    for i in range(int(nQuat)+1):
        offsetQuatOneJoint = offsetQuatNp[:-1, i*4:(i+1)*4]
        
        # Quaternion covariance matrix.
        covarianceMatrix = np.dot(offsetQuatOneJoint.T, offsetQuatOneJoint)
        
        # Quaternion averaging using the Eigenvector approach by Markley et al.
        eigenvalues, eigenvectors = eigh(covarianceMatrix)
        qAvg = eigenvectors[:, np.argmax(eigenvalues)]
        
        # Ensure unit quaternion.
        qAvg /= np.linalg.norm(qAvg)
        qAvgOsim = osim.Quaternion(qAvg[0],qAvg[1],qAvg[2],qAvg[3])
        
        averagesQuat[columnLabels[i*4][:-2]] = qAvgOsim
    
    # Average the Cartesian coordinates over time.
    for coordName in offsetCartDf.columns:
        averagesCart[coordName] = np.average(offsetCartDf[:-1][coordName])
    
    return averagesQuat, averagesCart

# This method maps coordinates from the TLO model to the Rajagopal model for a 
# single joint.
def mapJoint(mpdJointName : str,
             mpdModel : osim.Model,
             tloModel : osim.Model,
             errModel : osim.Model,
             mpdState : osim.State,
             tloState : osim.State,
             errState : osim.State,
             rotOffset = osim.Rotation(),
             cartOffset = [],
             signs = [1,1,1,1,1,1],
             rotationOrder = [Z_AXIS,
                              X_AXIS,
                              Y_AXIS],
             indicesToUseFromRotation = [0,1,2], # Indices (in oder) of the Euler angles extracted from the rotation matrix to use for the coordinates.
             rotationSequence = osim.BodyRotationSequence):
    
    # Realize positions to be able to extract rotation matrices of body frames.
    mpdModel.realizePosition(mpdState)
    tloModel.realizePosition(tloState)
    
    # Extract the Rajagopal joint object and its parent body.
    mpdJoint = mpdModel.getJointSet().get(mpdJointName)
    mpdParentName = mpdJoint.getParentFrame().getName().replace('_offset','')
    
    if mpdParentName == 'ground':
        mpdParentBody = mpdModel.getGround()
    else:
        mpdParentBody = mpdModel.getBodySet().get(mpdParentName)
    
    # Extract a coordinate from Rajagopal that also exists in TLO. Every
    # coordinate in Rajagopal (except for the patella coordinate) has an
    # equivalent TLO coordinate, so we just use the first coordinate of this
    # joint.
    commonCoord = mpdJoint.get_coordinates(0)
    commonCoord = tloModel.getCoordinateSet().get(commonCoord.getName())
    
    # Using the coordinate that is common between TLO and Rajagopal, extract the
    # TLO joint and child body for this Rajagopal joint.
    tloJoint = commonCoord.getJoint()
    tloChildName = tloJoint.getChildFrame().getName().replace('_offset','')
    tloChildBody = tloModel.getBodySet().get(tloChildName)
    
    # Obtain the rotation matrix of the Rajagopal child in terms of the
    # Rajagopal parent for mapping.
    mpdModel.realizePosition(mpdState)
    parentRot = mpdParentBody.getRotationInGround(mpdState)
    childRot = tloChildBody.getRotationInGround(tloState)
    inv = parentRot.invert()
    parentRotInv = IDENTITY_ROT.multiply(inv)
    finalRot = parentRotInv.multiply(childRot)
    finalRot = finalRot.multiply(rotOffset)
    
    # Obtain the coordinate values as Euler angles from the rotation matrix in
    # the correct sequence and order.
    coordsRot = finalRot.convertThreeAxesRotationToThreeAngles(rotationSequence,
                                                            *rotationOrder)
    
    coordsRotOffset = rotOffset.convertThreeAxesRotationToThreeAngles(rotationSequence,
                                                                 *rotationOrder)
    
    # Write the coordinates to the Rajagopal model.
    mpdNCoords = mpdJoint.numCoordinates()
    jointName = mpdJoint.getName()
    cTranslational = 0
    cRotational = 0
    appliedOffsets = {}
    for c in range(mpdNCoords):
        mpdCoord = mpdJoint.get_coordinates(c)
        coordName = mpdCoord.getName()
        coordNameFull = '/jointset/'+jointName+'/'+coordName+'/value'
        # Some rajagopal coordinates are defined in the -axis direction. Hip
        # abduction, for example is along the +x axis on the right leg and the
        # -x axis on the left leg.
        if (mpdCoord.getMotionType() == 1):
            coordValue = signs[c] * coordsRot.get(indicesToUseFromRotation[c])
            cRotational += 1
            appliedOffsets[coordName] = \
                coordsRotOffset.get(indicesToUseFromRotation[c]) * 180/np.pi
        elif (mpdCoord.getMotionType() == 2):
            appliedOffsets[coordName] = cartOffset[cTranslational]
            coordValue = signs[c] \
                * tloChildBody.getPositionInGround(tloState).get(cTranslational)\
                + cartOffset[cTranslational]
            cTranslational += 1
        
        mpdModel.setStateVariableValue(mpdState,coordNameFull,coordValue)
    
    # Write the unused coordinates to the error model.
    jointName = tloJoint.getName()
    for c in range(tloJoint.numCoordinates()):
        tloCoord = tloJoint.get_coordinates(c)
        coordName = tloCoord.getName()
        if not coordinateNameInModel(coordName, mpdModel):
            if c in [0,1,2]:
                coordNameFull = '/jointset/'+jointName+'/'+coordName+'/value'
                coordValue = coordsRot.get(c)
                errModel.setStateVariableValue(errState,coordNameFull,coordValue)
    
    return appliedOffsets

# Map all joints.
def mapAll(tloModel         : osim.Model,
           tloData          : pandas.DataFrame,
           mpdModel         : osim.Model,
           mpdDataFileName  : str,
           errModel         : osim.Model,
           errDataFileName  : str,
           offsetDictQuat   : dict,
           offsetDictCart   : dict):
    
    offsetDictRot = {}
    rotIdentity = osim.Rotation()
    for key in offsetDictQuat.keys():
        offsetRot = rotIdentity.setRotationFromQuaternion(offsetDictQuat[key])
        offsetRot = osim.Rotation(offsetRot)
        offsetDictRot[key] = offsetRot
    
    tloNTimeSteps = tloData.shape[0]
    fileCoords = tloData.columns[1:]
    tloTimeArray = tloData['time']
    
    tloState    = tloModel.initSystem()
    tloCoordSet = tloModel.getCoordinateSet()
    
    mpdState    = mpdModel.initSystem()
    
    errState = errModel.initSystem()
    
    mpdMFG = MotFileGenerator(fileName = mpdDataFileName,
                              nTimeSteps = tloNTimeSteps,
                              model = mpdModel)
    
    errMFG = MotFileGenerator(fileName = errDataFileName,
                              nTimeSteps = tloNTimeSteps,
                              model = errModel)
    
    # Map TLO coordinates to Rajagopal coordinates for each time-step.
    for timeStep, timeSec in enumerate(tloTimeArray):
        tloState.setTime(timeSec)
        mpdState.setTime(timeSec)
        errState.setTime(timeSec)
        
        # Set the TLO model coordinates at this time-step according to the IK
        # results.
        for c, coordName in enumerate(fileCoords):
            coord = tloCoordSet.get(coordName)
            jointName = coord.getJoint().getName()
            coordNameFull = '/jointset/'+jointName+'/'+coordName+'/value'
            coordVal = tloData.at[timeStep,coordName]
            # Convert rotational coordinates from degrees to radians.
            if (tloData.inDegrees and coord.getMotionType()==1):
                coordVal = coordVal * np.pi/180
            tloModel.setStateVariableValue(tloState, coordNameFull, coordVal)
        
        appliedOffsets = mapJoint('ground_pelvis',
                                  mpdModel,
                                  tloModel,
                                  errModel,
                                  mpdState,
                                  tloState,
                                  errState,
                                  rotOffset = offsetDictRot['ground_pelvis'],
                                  cartOffset = [offsetDictCart['pelvis_tx'],
                                                offsetDictCart['pelvis_ty'],
                                                offsetDictCart['pelvis_tz']])
        
        
        
        # Map each of TLO's joint angles to Rajagopal joint angles.
        appliedOffsetsTemp = mapJoint('hip_r',
                    mpdModel,
                    tloModel,
                    errModel,
                    mpdState,
                    tloState,
                    errState,
                    rotOffset = offsetDictRot['hip_r'])
        appliedOffsets = {**appliedOffsets, **appliedOffsetsTemp}
        
